enc = [
    0xDD, 0x7F, 0xDF, 0x3D, 0x93, 0x04, 0x77, 0x55,
    0x4A, 0x9B, 0xAB, 0x9D, 0xEF, 0xCC, 0x5B, 0x71,
    0xFF, 0xE7, 0xEB, 0xB4, 0xB8, 0xC0, 0xFF, 0xE1,
    0x60, 0x10, 0xA7, 0x1B, 0x05, 0xD1, 0x54, 0x3C,
    0xC0, 0xAC, 0xDC, 0xCC, 0x41
]

# The decryption key
key = 0xCCBBAA8869423713

# Extract key bytes in correct order (little endian as Go runtime uses)
key_bytes = list(key.to_bytes(8, byteorder='little'))

flag = ""

for i in range(len(enc)):
    v = enc[i]

    # Step 1: XOR with (3*i + 85)
    v ^= (3 * i + 85) & 0xFF

    # Step 2: Swap nibbles
    v = ((v & 0xF0) >> 4) | ((v & 0x0F) << 4)

    # Step 3: Subtract (7*i + 23)
    v = (v - (7 * i + 23)) & 0xFF

    # Step 4: XOR with key byte
    v ^= key_bytes[i % 8]

    flag += chr(v)

print("Flag:", flag)
